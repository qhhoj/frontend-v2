// Writes solved palettes (solve.mjs) as one CSS file each under src/theme/palette/, already in Prettier's format. The
// default palette (the first) is scoped by `:root` alone; the others by `:root[data-palette='<id>']`, which outranks it.
import { hexToRgb } from './color.mjs';
import { LANES, PARTIAL_ALPHAS } from './paper.mjs';

const header = (palette) =>
  `/* Generated by \`npm run palette\` (scripts/palette/) from the \`${palette.id}\` inputs in scripts/palette/palettes.mjs. Do not edit: change the inputs and regenerate. */`;

/** The palette's root selector: `:root` for the default palette, else `:root` carrying its `data-palette`. */
const rootOf = (palette) => (palette.isDefault ? ':root' : `:root[data-palette='${palette.id}']`);

/** A hex in lower case, or a tint as `rgba()`. */
function value(colour) {
  if (typeof colour === 'string') return colour.toLowerCase();
  const [red, green, blue] = hexToRgb(colour.hex).map((channel) => Math.round(channel * 255));
  return `rgba(${red}, ${green}, ${blue}, ${colour.alpha})`;
}

const rule = (selectors, declarations) =>
  `${selectors.join(',\n')} {\n${declarations.map(([name, colour]) => `  ${name}: ${value(colour)};`).join('\n')}\n}\n`;
const token = (name, colour) => [`--qh-${name}`, colour];

const textTokens = ({ neutrals }) => [
  token('text', neutrals.text),
  token('text-secondary', neutrals.textSecondary),
  token('text-muted', neutrals.textMuted),
  token('line-control', neutrals.lineControl),
];

const accentTokens = (accent) => [
  token('accent', accent.fill),
  token('accent-strong', accent.strong),
  token('on-accent', accent.on),
  token('accent-text', accent.text),
  token('accent-soft', accent.soft),
  token('accent-soft-text', accent.softText),
  token('focus-ring', accent.ring),
];

const laneTokens = ({ lanes, firstSolve }) => [
  ...LANES.flatMap((lane) => [
    token(`verdict-${lane}`, lanes[lane].text),
    token(`verdict-${lane}-bg`, lanes[lane].tint),
    token(`verdict-${lane}-solid`, lanes[lane].solid),
    token(`verdict-${lane}-on`, lanes[lane].on),
  ]),
  token('first-solve-bg', firstSolve.fill),
  token('first-solve-text', firstSolve.on),
];

/** Tokens that do not change with the accent or the contrast level. */
const fixedTokens = (set, mode) => [
  token('ground', set.neutrals.ground),
  token('surface', set.neutrals.surface),
  token('surface-strong', set.neutrals.strong),
  token('surface-hover', set.neutrals.hover),
  token('line', set.neutrals.line),
  token('line-strong', set.neutrals.lineStrong),
  ...PARTIAL_ALPHAS.map((alpha, index) =>
    token(`partial-bg-${index + 1}`, { hex: set.lanes.ac.tint.hex, alpha }),
  ),
  ...set.tags.flatMap((tag, index) => [
    token(`tag-${index + 1}`, tag.text),
    token(`tag-${index + 1}-bg`, tag.tint),
    token(`tag-${index + 1}-dot`, tag.dot),
  ]),
  ...set.difficulty.map((hex, index) => token(`diff-${index + 1}`, hex)),
  ...Object.entries(set.tiers).map(([name, hex]) => token(`tier-${name}`, hex)),
  ...Object.entries(set.medals).map(([name, hex]) => token(`medal-${name}`, hex)),
  ...Object.entries(set.syntax).map(([name, hex]) => token(`syntax-${name}`, hex)),
  [
    '--qh-shadow-float',
    `0 8px 24px ${value({ hex: mode === 'light' ? set.neutrals.text : '#000000', alpha: mode === 'light' ? 0.12 : 0.55 })}`,
  ],
  token('qr-ink', '#141413'),
  token('qr-paper', '#FFFFFF'),
];

const coinTokens = (set) => [
  ...set.coins.map(([top, bottom], index) => [
    `--qh-coin-${index + 1}`,
    `linear-gradient(135deg, ${value(top)}, ${value(bottom)})`,
  ]),
  token('on-coin', set.ink),
];

/** The base file of a mode: every colour token at standard contrast, with the default accent. */
function modeCss(palette, mode, set) {
  const themedRoot = `${rootOf(palette)}[data-theme='${mode}']`;
  const selectors = mode === 'light' && palette.isDefault ? [':root', themedRoot] : [themedRoot];
  const declarations = [
    ['color-scheme', mode],
    ...fixedTokens(set, mode),
    ...textTokens(set),
    ...accentTokens(set.accents[palette.defaultAccent]),
    ...laneTokens(set),
    ...coinTokens(set),
    ['--qh-bit-halo', mode === 'light' ? 'transparent' : 'var(--qh-text-muted)'],
  ];
  return rule(selectors, declarations);
}

const themed = (palette, mode, high) =>
  `${rootOf(palette)}[data-theme='${mode}']${high ? "[data-contrast='high']" : ''}`;

/** The high-contrast overlay: text, control borders, the default accent and the verdict lanes, per mode. */
function contrastCss(palette, highSets) {
  const rules = Object.entries(highSets).map(([mode, set]) =>
    rule(
      [themed(palette, mode, true)],
      [...textTokens(set), ...accentTokens(set.accents[palette.defaultAccent]), ...laneTokens(set)],
    ),
  );
  return rules.join('\n');
}

/** One rule per mode, contrast level and accent: on <html> (`data-accent`) and on any element (the picker's swatches). */
function accentsCss(palette, setsByLevel) {
  const rules = [];
  for (const [level, sets] of Object.entries(setsByLevel))
    for (const [mode, set] of Object.entries(sets))
      for (const id of Object.keys(palette.accents)) {
        const root = themed(palette, mode, level === 'high');
        rules.push(
          rule(
            [`${root}[data-accent='${id}']`, `${root} [data-accent='${id}']`],
            accentTokens(set.accents[id]),
          ),
        );
      }
  return rules.join('\n');
}

/** The palette's whole file: both modes, the high-contrast overlay, then the accents (their rules outrank the overlay's default accent). */
export const paletteCss = (palette, sets) =>
  [
    header(palette),
    modeCss(palette, 'light', sets.standard.light),
    modeCss(palette, 'dark', sets.standard.dark),
    contrastCss(palette, sets.high),
    accentsCss(palette, sets),
  ].join('\n');
