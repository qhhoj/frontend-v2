import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
/** Where the snapshot and the types live; the override exists for the script's own spec. */
const GENERATED_DIR = resolve(process.env.API_GEN_DIR ?? resolve(root, 'src/api/generated'));
const SNAPSHOT = resolve(GENERATED_DIR, 'openapi.json');
const SCHEMA = resolve(GENERATED_DIR, 'schema.d.ts');
const SOURCE = resolve(GENERATED_DIR, 'openapi.source');
const DEFAULT_SOURCE = resolve(root, '../backend-v2/openapi.json');
const BANNER =
  '/** Generated by `npm run api:gen` from openapi.json (the backend contract). Do not edit. */\n\n';
const sourcePath = () => resolve(process.env.OPENAPI_SPEC ?? DEFAULT_SOURCE);

/** The TypeScript declarations for the OpenAPI document at `specPath`. */
async function generateSchema(specPath) {
  const ast = await openapiTS(pathToFileURL(specPath), { alphabetize: true });
  return BANNER + astToString(ast);
}

function fail(message) {
  console.error(message);
  process.exit(1);
}

const gitOutput = (cwd, args) => spawnSync('git', args, { cwd, encoding: 'utf8' });

/** The backend commit the document at `specPath` belongs to: `<sha>`, `<sha>-dirty` when the file has uncommitted changes, `unknown` outside git. */
function sourceRevision(specPath) {
  if (process.env.OPENAPI_SOURCE_SHA) return process.env.OPENAPI_SOURCE_SHA;
  const cwd = dirname(specPath);
  const head = gitOutput(cwd, ['rev-parse', 'HEAD']);
  if (head.status !== 0) return 'unknown';
  const changes = gitOutput(cwd, ['status', '--porcelain', '--', specPath]);
  return head.stdout.trim() + (changes.stdout.trim() ? '-dirty' : '');
}

/** Copies the backend's document next to the types, records where it came from, then generates from the copy. */
async function sync(from) {
  if (!existsSync(from))
    fail(`No OpenAPI document at ${from}: set OPENAPI_SPEC to the backend's openapi.json.`);
  mkdirSync(GENERATED_DIR, { recursive: true });
  copyFileSync(from, SNAPSHOT);
  writeFileSync(SOURCE, `${sourceRevision(from)}\n`);
  writeFileSync(SCHEMA, await generateSchema(SNAPSHOT));
  console.log(`api:gen ${from} -> ${SCHEMA}`);
}

/** Fails when the snapshot differs from the backend's document; says so and passes when there is no backend checkout. */
function checkAgainstBackend(backendPath) {
  if (!existsSync(backendPath)) {
    console.log(`api:check --backend skipped: no backend document at ${backendPath}`);
    return;
  }
  if (!readFileSync(backendPath).equals(readFileSync(SNAPSHOT)))
    fail(
      `src/api/generated/openapi.json differs from ${backendPath}: run \`npm run api:gen\`, review the diff and commit it.`,
    );
}

/** Fails when schema.d.ts is not what the committed snapshot generates (and, with --backend, when the snapshot lags the backend). */
async function check({ againstBackend }) {
  if (!existsSync(SNAPSHOT) || !existsSync(SCHEMA))
    fail(
      'src/api/generated/ has no snapshot or schema.d.ts: run `npm run api:gen` and commit the result.',
    );
  const fresh = await generateSchema(SNAPSHOT);
  if (fresh !== readFileSync(SCHEMA, 'utf8'))
    fail('src/api/generated/schema.d.ts is stale: run `npm run api:gen` and commit the result.');
  if (againstBackend) checkAgainstBackend(sourcePath());
}

if (process.argv.includes('--check'))
  await check({ againstBackend: process.argv.includes('--backend') });
else await sync(sourcePath());
